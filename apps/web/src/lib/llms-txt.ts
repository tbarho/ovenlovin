const PITCH = "The family recipe box your AI can actually use, and it knows who can't eat what.";

export function buildLlmsTxt(origin: string): string {
  const base = origin.replace(/\/$/, "") || "https://ovenlovin.vercel.app";
  return [
    `# OvenLovin`,
    ``,
    `> ${PITCH}`,
    ``,
    `Open-source recipe box and meal planner for families and their AI agents.`,
    `Per-person allergen checks (US Big 9 + EU 14). MIT license.`,
    `Not medical advice. Always check ingredient labels before serving.`,
    ``,
    `## This instance`,
    ``,
    `- Home: ${base}/`,
    `- Docs: ${base}/docs`,
    `- Connect your agent: ${base}/docs/connect-your-agent`,
    `- MCP (Streamable HTTP): ${base}/mcp`,
    `- REST: ${base}/api/v1`,
    `- OpenAPI: ${base}/api/v1/openapi.json`,
    ``,
    `## Auth`,
    ``,
    `Send one of:`,
    `- \`Authorization: ApiKey rkapi_...\``,
    `- \`Authorization: Bearer rkapi_...\``,
    ``,
    `Create a key in Settings after signing in. Unauthenticated REST returns problem+json 401.`,
    `Unauthenticated MCP POST returns a JSON-RPC error envelope (HTTP 401).`,
    ``,
    `## MCP tools`,
    ``,
    `- whoami`,
    `- search_recipes, get_recipe, create_recipe, import_recipe, delete_recipe`,
    `- get_household_context, manage_household_schedule, get_person_rules, manage_people, manage_person_rules, manage_person_loves, reorder_people`,
    `- check_meal_plan, save_meal_plan, get_meal_plan, delete_meal_plan, export_shopping_list`,
    `- list_cookbooks, get_cookbook, manage_cookbook`,
    ``,
    `## REST (selected)`,
    ``,
    `- GET /api/v1/status (commitSha = VERCEL_GIT_COMMIT_SHA)`,
    `- GET/POST /api/v1/recipes`,
    `- GET/PATCH/DELETE /api/v1/recipes/{id}`,
    `- POST /api/v1/recipes/import`,
    `- GET/POST /api/v1/people`,
    `- GET/POST /api/v1/people/{id}/rules`,
    `- GET/POST /api/v1/people/{id}/preferences`,
    `- GET/POST /api/v1/meal-plans`,
    `- GET /api/v1/meal-plans/{id}/check`,
    `- GET /api/v1/meal-plans/{id}/shopping-list`,
    `- GET/PATCH /api/v1/meal-plans/{id}/shopping-list/state`,
    `- GET/POST /api/v1/cookbooks`,
    `- GET /api/v1/households`,
    `- GET/PUT /api/v1/households/schedule`,
    `- GET/POST /api/v1/api-keys`,
    ``,
    `## Safety`,
    ``,
    `Rule checking is deterministic and per-person. Findings name the person, rule, ingredient, and reason.`,
    `Incomplete checks return status: incomplete - never "no issues".`,
    `This is not medical advice. Always read labels.`,
    ``,
    `## Full docs`,
    ``,
    `- ${base}/docs`,
    `- https://tbarho.github.io/ovenlovin/`,
    ``,
  ].join("\n");
}

export const OVENLOVIN_PITCH = PITCH;
